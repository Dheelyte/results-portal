"use client";

/**
 * The score entry grid (ARCHITECTURE.md §8.1).
 *
 * The requirement this is built against, in full: "Teachers will use this on
 * an Android phone, on patchy data, for 30 pupils across up to eight numeric
 * columns. If it is slower than their current paper sheet they will not use
 * the portal."
 *
 * So:
 *
 * - **One DOM for both layouts.** Below 640px CSS turns each row into a card
 *   (`.score-grid` in globals.css) rather than a second set of inputs being
 *   rendered and hidden. Two sets would mean two refs per cell, duplicate
 *   ids, and keyboard focus landing on an invisible field.
 * - **The columns come from the server.** `sheet.columns` is the card's own
 *   column list for that half, so the first-half and second-half sheets of
 *   §8.1 are this one component and neither layout can drift.
 * - **Nothing computed here.** CA Test Total is generated by Postgres (R2)
 *   and the period average and grade by `services/grading.py` (R3, R4). The
 *   grid displays what the save returned. Recomputing them in the browser is
 *   how a portal comes to disagree with its own report card.
 * - **Validation is immediate and inline** — a red cell naming the maximum,
 *   never a modal — and the server is still the authority. The local check
 *   mirrors R1; it does not replace it.
 */

import { useCallback, useEffect, useMemo, useRef, useState } from "react";

import { Badge, Notice } from "@/components/ui";
import { ApiError } from "@/lib/api/client";
import type { EntryRow, Sheet, TeacherApi } from "@/lib/api/teacher";
import { clearDraft, readDraft, unreconciled, writeDraft, type Draft } from "@/lib/drafts";
import {
  countCells,
  errorsIn,
  isEmpty,
  labelOf,
  merge,
  payloadFrom,
  plain,
  type Cells,
} from "@/lib/scores";
import { autosaveLabel, useAutosave } from "@/lib/use-autosave";

/** The sheet's stored values, as the strings the inputs hold. */
function serverCells(sheet: Sheet): Cells {
  const cells: Cells = {};
  for (const row of sheet.rows ?? []) {
    const columns: Record<string, string> = {};
    for (const column of sheet.columns) {
      const value = (row as unknown as Record<string, string | null>)[column];
      columns[column] = value === null || value === undefined ? "" : plain(value);
    }
    cells[row.pupil_id] = columns;
  }
  return cells;
}

export function ScoreGrid({ sheet, api }: { sheet: Sheet; api: TeacherApi }) {
  const saved = useMemo(() => serverCells(sheet), [sheet]);
  const maxima = sheet.maxima ?? null;

  const [values, setValues] = useState<Cells>(saved);
  const [dirty, setDirty] = useState<Cells>({});
  const [rejections, setRejections] = useState<Record<string, Record<string, string>>>({});
  const [recovered, setRecovered] = useState<Draft | null>(null);
  const [failure, setFailure] = useState<string | null>(null);

  const entry = useRef<Map<string, HTMLInputElement>>(new Map());
  const periodId = sheet.assessment_period_id;
  const classSubjectId = sheet.class_subject_id;
  const locked = !sheet.editable || !sheet.maxima_configured;

  /* --- Recovery (§8.1: "reconcile on reload and say what was recovered") -- */
  useEffect(() => {
    const draft = readDraft(classSubjectId, periodId);
    if (!draft) return;

    const pending = unreconciled(draft.values, saved);
    if (isEmpty(pending)) {
      // The draft was written just before a save that did land. Nothing to
      // recover, and saying so would teach the teacher to ignore the notice.
      clearDraft(classSubjectId, periodId);
      return;
    }

    setValues((current) => merge(current, pending));
    setDirty((current) => merge(current, pending));
    setRecovered({ values: pending, at: draft.at });
  }, [classSubjectId, periodId, saved]);

  /* --- The draft follows the dirty set -------------------------------- */
  useEffect(() => {
    writeDraft(classSubjectId, periodId, dirty);
  }, [classSubjectId, periodId, dirty]);

  const localErrors = useMemo(
    () =>
      errorsIn(values, sheet.columns, maxima as unknown as Record<string, string | null> | null),
    [values, maxima, sheet.columns],
  );

  const dirtyCount = countCells(dirty);
  const hasLocalErrors = Object.keys(localErrors).length > 0;

  /* --- Saving -------------------------------------------------------- */
  const save = useCallback(async () => {
    // A row with a cell the teacher is still fixing is held back rather than
    // sent: the save applies all or none, so one bad cell would reject the
    // whole class's work.
    const clean: Cells = Object.fromEntries(
      Object.entries(dirty).filter(([pupilId]) => !localErrors[pupilId]),
    );
    const payload = payloadFrom(clean) as unknown as EntryRow[];

    if (payload.length === 0) return;

    const sent = payload.map((row) => row.pupil_id);
    try {
      await api.saveEntries(classSubjectId, periodId, payload);
    } catch (caught) {
      if (caught instanceof ApiError && caught.status === 422) {
        setRejections(caught.rows ?? {});
        setFailure(caught.message);
      } else if (caught instanceof ApiError && caught.status !== 0) {
        setFailure(caught.message);
      }
      throw caught;
    }

    // Only the rows that went out are clean. A cell changed while the request
    // was in flight is still dirty, and the next tick will carry it.
    setRejections({});
    setFailure(null);
    setDirty((current) => {
      const remaining: Cells = {};
      for (const [pupilId, row] of Object.entries(current)) {
        if (!sent.includes(pupilId)) remaining[pupilId] = row;
      }
      return remaining;
    });
    clearDraft(classSubjectId, periodId);
  }, [api, classSubjectId, dirty, localErrors, periodId]);

  const autosave = useAutosave({
    hasPending: dirtyCount > 0 && !hasLocalErrors,
    save,
    // A 422 fails the same way every time, so retrying it would spin a
    // "Saving…" label for as long as the teacher left the cell alone.
    isRetryable: (error) => !(error instanceof ApiError && error.status === 422),
    enabled: !locked,
  });

  /* --- Editing ------------------------------------------------------- */
  const change = useCallback(
    (pupilId: string, column: string, raw: string) => {
      setValues((current) => ({
        ...current,
        [pupilId]: { ...(current[pupilId] ?? {}), [column]: raw },
      }));

      setDirty((current) => {
        const row = { ...(current[pupilId] ?? {}) };
        if (raw === (saved[pupilId]?.[column] ?? "")) {
          // Typed back to what the server holds, so there is nothing to save.
          delete row[column];
        } else {
          row[column] = raw;
        }
        const next = { ...current, [pupilId]: row };
        if (Object.keys(row).length === 0) delete next[pupilId];
        return next;
      });

      setRejections((current) => {
        const row = { ...(current[pupilId] ?? {}) };
        delete row[column];
        return { ...current, [pupilId]: row };
      });
    },
    [saved],
  );

  /** Enter and ↓ move down the same column; Tab moves across (§8.1). */
  const onKeyDown = useCallback(
    (event: React.KeyboardEvent<HTMLInputElement>, rowIndex: number, column: string) => {
      const step = event.key === "ArrowUp" ? -1 : 1;
      if (event.key !== "Enter" && event.key !== "ArrowDown" && event.key !== "ArrowUp") return;

      const rows = sheet.rows ?? [];
      const target = rows[rowIndex + step];
      if (!target) return;

      event.preventDefault();
      entry.current.get(`${target.pupil_id}:${column}`)?.focus();
    },
    [sheet.rows],
  );

  const rows = sheet.rows ?? [];

  return (
    <div className="flex flex-col gap-4">
      {recovered ? (
        <Notice tone="warning">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <span>
              Recovered {countCells(recovered.values)} unsaved{" "}
              {countCells(recovered.values) === 1 ? "score" : "scores"} from this device, last
              changed{" "}
              {new Date(recovered.at).toLocaleString("en-NG", { timeZone: "Africa/Lagos" })}. They
              are in the grid below but not yet saved.
            </span>
            <span className="flex gap-2">
              <button
                type="button"
                className="rounded-md border border-[var(--border)] px-3 py-1 text-sm"
                onClick={() => {
                  setValues(saved);
                  setDirty({});
                  clearDraft(classSubjectId, periodId);
                  setRecovered(null);
                }}
              >
                Discard them
              </button>
              <button
                type="button"
                className="rounded-md border border-[var(--border)] px-3 py-1 text-sm"
                onClick={() => {
                  setRecovered(null);
                  autosave.saveNow();
                }}
              >
                Save them now
              </button>
            </span>
          </div>
        </Notice>
      ) : null}

      {!sheet.maxima_configured ? (
        <Notice tone="warning">
          The Marks Obtainable row for this sheet has not been set up, so there is nothing to
          check scores against. Ask the administrator to set a maximum for each column before
          entering marks.
        </Notice>
      ) : null}

      {!sheet.editable && sheet.maxima_configured ? (
        <Notice tone="info">
          {sheet.state === "submitted"
            ? "This class has been submitted for review, so its scores are read-only. Ask the head teacher to return it if a correction is needed."
            : "This class has been approved, so its scores are final. Only an administrator may change them now."}
        </Notice>
      ) : null}

      {failure ? <Notice tone="error">{failure}</Notice> : null}

      <div className="flex flex-wrap items-center justify-between gap-3">
        <p
          aria-live="polite"
          className="text-sm text-[var(--muted)]"
          data-testid="autosave-status"
        >
          {autosaveLabel(autosave.state, autosave.savedAt)}
          {dirtyCount > 0 ? ` · ${dirtyCount} unsaved` : ""}
        </p>
        <button
          type="button"
          onClick={autosave.saveNow}
          disabled={locked || dirtyCount === 0 || hasLocalErrors || autosave.state === "saving"}
          className="rounded-md bg-[var(--accent)] px-4 py-2 text-sm font-medium text-white disabled:opacity-50"
        >
          Save now
        </button>
      </div>

      <div className="score-grid overflow-x-auto">
        <table className="w-full border-collapse text-sm">
          <thead>
            <tr>
              <th scope="col" className="cell head sticky-name">
                Pupil
              </th>
              {sheet.columns.map((column) => (
                <th scope="col" key={column} className="cell head">
                  {labelOf(column)}
                </th>
              ))}
              <th scope="col" className="cell head">
                CA Total
              </th>
              <th scope="col" className="cell head">
                Average
              </th>
              <th scope="col" className="cell head">
                Grade
              </th>
            </tr>
            {/* §8.1: the Marks Obtainable row pins to the top of the grid. */}
            <tr className="maxima">
              <th scope="row" className="cell head sticky-name">
                Marks Obtainable
              </th>
              {sheet.columns.map((column) => (
                <td key={column} className="cell numeric font-medium">
                  {plain((maxima as unknown as Record<string, string | null>)?.[column])}
                </td>
              ))}
              <td className="cell" colSpan={3}>
                {maxima?.is_class_override ? "Set for this class" : "School-wide"}
              </td>
            </tr>
          </thead>

          <tbody>
            {rows.map((row, rowIndex) => (
              <tr key={row.pupil_id} className="card">
                <th scope="row" className="cell name sticky-name">
                  <span className="block font-medium">
                    {row.last_name}, {row.first_name}
                  </span>
                  <span className="block text-xs text-[var(--muted)]">
                    {row.admission_number}
                  </span>
                </th>

                {sheet.columns.map((column) => {
                  const maximum = (maxima as unknown as Record<string, string | null>)?.[column];
                  const error = localErrors[row.pupil_id]?.[column] ?? rejections[row.pupil_id]?.[column];
                  const id = `${row.pupil_id}:${column}`;
                  return (
                    <td
                      key={column}
                      className="cell"
                      data-label={`${labelOf(column)} / ${plain(maximum)}`}
                    >
                      <input
                        ref={(element) => {
                          if (element) entry.current.set(id, element);
                          else entry.current.delete(id);
                        }}
                        value={values[row.pupil_id]?.[column] ?? ""}
                        onChange={(event) => change(row.pupil_id, column, event.target.value)}
                        onBlur={autosave.saveNow}
                        onKeyDown={(event) => onKeyDown(event, rowIndex, column)}
                        disabled={locked}
                        // The Android numeric keypad, which is the whole point
                        // of §8.1's "on an Android phone".
                        inputMode="decimal"
                        aria-label={`${labelOf(column)} for ${row.last_name}, ${row.first_name}`}
                        aria-invalid={error ? true : undefined}
                        aria-errormessage={error ? `${id}-error` : undefined}
                        className={`score-input ${error ? "invalid" : ""}`}
                      />
                      {error ? (
                        <span id={`${id}-error`} className="score-error" role="alert">
                          {error}
                        </span>
                      ) : null}
                    </td>
                  );
                })}

                <td className="cell numeric computed" data-label="CA Total">
                  {plain(row.ca_test_total)}
                </td>
                <td className="cell numeric computed" data-label="Average">
                  {plain(row.period_average)}
                </td>
                <td className="cell computed" data-label="Grade">
                  {row.grade_letter ?? row.grade?.letter ?? "—"}
                  {row.grade?.remark ? (
                    <span className="block text-xs text-[var(--muted)]">{row.grade.remark}</span>
                  ) : null}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {rows.length === 0 ? (
        <Notice tone="info">
          No pupils are enrolled in this class for this session yet.
        </Notice>
      ) : null}

      <p className="text-xs text-[var(--muted)]">
        <Badge tone="neutral">Enter</Badge> and <Badge tone="neutral">↓</Badge> move down the
        same column; <Badge tone="neutral">Tab</Badge> moves across. CA Total, the average and
        the grade are calculated and cannot be typed.
      </p>
    </div>
  );
}
