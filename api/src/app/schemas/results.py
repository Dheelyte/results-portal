"""Request and response models for score entry (§7, §8.1)."""

import datetime as dt
import decimal
import uuid

from pydantic import BaseModel, ConfigDict, Field

from app.models import ClassTermState, TermHalf
from app.schemas.common import OrmModel, ScoreValue
from app.services.marks import ALL_COLUMNS

# The grid sends only the cells the teacher touched, so an omitted column must
# mean "leave it alone" and an explicit null must mean "clear it". Pydantic
# distinguishes the two through `model_fields_set`, which is why these are
# read back with `exclude_unset=True` rather than from a plain dict.
SCORE_COLUMNS = frozenset(ALL_COLUMNS)


class EntryRow(BaseModel):
    """One pupil's cells, as the grid submits them."""

    model_config = ConfigDict(extra="forbid")

    pupil_id: uuid.UUID

    ca_test_1: ScoreValue | None = None
    ca_test_2: ScoreValue | None = None
    ca_test_3: ScoreValue | None = None
    ca_test_4: ScoreValue | None = None
    ca_test_5: ScoreValue | None = None
    mid_term_test: ScoreValue | None = None
    exam: ScoreValue | None = None

    def provided_scores(self) -> dict[str, decimal.Decimal | None]:
        """Only the columns actually present in the request body."""
        return self.model_dump(include=set(SCORE_COLUMNS), exclude_unset=True)


class EntriesSave(BaseModel):
    """A bulk upsert of one sheet. Applied all or none (§7)."""

    model_config = ConfigDict(extra="forbid")

    assessment_period_id: uuid.UUID
    # A class is thirty pupils; the ceiling is generous rather than tight, but
    # an unbounded array is an unbounded transaction.
    rows: list[EntryRow] = Field(min_length=1, max_length=400)


class MaximaRead(OrmModel):
    """The Marks Obtainable row, which §8.1 pins to the top of the grid."""

    ca_test_1: decimal.Decimal | None = None
    ca_test_2: decimal.Decimal | None = None
    ca_test_3: decimal.Decimal | None = None
    ca_test_4: decimal.Decimal | None = None
    ca_test_5: decimal.Decimal | None = None
    mid_term_test: decimal.Decimal | None = None
    exam: decimal.Decimal | None = None
    # True when the school set a row for this class specifically, rather than
    # the one that covers every class.
    is_class_override: bool = False


class GradeRead(BaseModel):
    """The grade shown during entry, resolved live from the active scale (R4).

    Not a snapshot. `grade_letter` on the row stays null until approval, and
    this field disappears once it is set — at which point the snapshot is what
    the card says and recomputing it is forbidden (CLAUDE.md rule 6).
    """

    letter: str
    remark: str


class EntryRead(BaseModel):
    """One line of the grid as rendered."""

    pupil_id: uuid.UUID
    admission_number: str
    first_name: str
    middle_name: str | None = None
    last_name: str

    ca_test_1: decimal.Decimal | None = None
    ca_test_2: decimal.Decimal | None = None
    ca_test_3: decimal.Decimal | None = None
    ca_test_4: decimal.Decimal | None = None
    ca_test_5: decimal.Decimal | None = None
    # R2, generated by Postgres. Read-only here and in the grid.
    ca_test_total: decimal.Decimal | None = None
    mid_term_test: decimal.Decimal | None = None
    exam: decimal.Decimal | None = None

    period_average: decimal.Decimal | None = None
    grade: GradeRead | None = None
    # Set only after approval, when it stops being computed (§4.5).
    grade_letter: str | None = None

    updated_at: dt.datetime | None = None


class SheetRead(BaseModel):
    """One class-subject's grid for one assessment period."""

    class_subject_id: uuid.UUID
    class_id: uuid.UUID
    class_name: str
    subject_id: uuid.UUID
    subject_name: str

    assessment_period_id: uuid.UUID
    term_id: uuid.UUID
    half: TermHalf
    # The columns this sheet carries, in card order. The grid renders what is
    # here rather than deciding for itself, so the two layouts of §8.1 are one
    # component (docs/DECISIONS.md D49).
    columns: list[str]

    maxima: MaximaRead | None = None
    # False when the Marks Obtainable row is missing or incomplete: R1 then
    # has nothing to validate against and the grid must say so rather than
    # accept scores it cannot check.
    maxima_configured: bool

    state: ClassTermState
    # False once the class is submitted or approved (R14).
    editable: bool

    rows: list[EntryRead] = Field(default_factory=list)


class TermSummary(BaseModel):
    """Which term the teacher is working in.

    Sent with the assignment list because §5.2 gives the calendar to the admin
    alone: a teacher has no endpoint that would tell them which term is
    current or what its two sheets are (docs/DECISIONS.md D51).
    """

    id: uuid.UUID
    number: str
    academic_session_name: str
    starts_on: dt.date | None = None
    ends_on: dt.date | None = None
    times_school_opened: int | None = None


class PeriodSummary(BaseModel):
    """One of the term's two sheets (§1.1)."""

    id: uuid.UUID
    half: TermHalf
    opens_on: dt.date | None = None
    closes_on: dt.date | None = None


class AssignmentRead(BaseModel):
    """One line of a teacher's own list of sheets (§7 /my/assignments)."""

    class_subject_id: uuid.UUID
    class_id: uuid.UUID
    class_name: str
    subject_id: uuid.UUID
    subject_name: str
    pupil_count: int
    # Keyed by the half's value, counting pupils with at least one CA score.
    # A progress hint, not R10's completeness check.
    entered_count: dict[str, int] = Field(default_factory=dict)
    state: ClassTermState


class WorkloadRead(BaseModel):
    """Everything the teacher's first screen needs, in one request."""

    term: TermSummary
    periods: list[PeriodSummary] = Field(default_factory=list)
    assignments: list[AssignmentRead] = Field(default_factory=list)
