"""R3's period average and R4's grade lookup, as pure functions.

The arithmetic in `services/grading.py` is a **placeholder** — N3 is
unanswered — so these tests do two jobs at once. They prove the properties
that will still hold whatever the school answers (scale-free, blanks as zero,
a column off the sheet counts for nothing), and they pin the parts that are a
guess, so that answering N3 means changing a test on purpose rather than
discovering the change on results night.
"""

from decimal import Decimal

import pytest

from app.models import GradeBand, TermHalf
from app.services.grading import (
    band_for,
    banded_value,
    mid_term_average,
    period_average,
    total_weighted_average,
)

# The card's seven bands (§1.3), highest first, as `create_scale` stores them.
CARD_BANDS = [
    GradeBand(letter="A+", remark="Excellence", min_score=Decimal(90), max_score=Decimal(100)),
    GradeBand(letter="A", remark="Very Good", min_score=Decimal(80), max_score=Decimal(89)),
    GradeBand(letter="B+", remark="Good", min_score=Decimal(70), max_score=Decimal(79)),
    GradeBand(letter="B", remark="Fairly Good", min_score=Decimal(60), max_score=Decimal(69)),
    GradeBand(letter="C", remark="Average", min_score=Decimal(50), max_score=Decimal(59)),
    GradeBand(letter="D", remark="Below Average", min_score=Decimal(40), max_score=Decimal(49)),
    GradeBand(letter="E", remark="Weak", min_score=Decimal(0), max_score=Decimal(39)),
]


def maxima(**overrides: int | None) -> dict[str, Decimal | None]:
    """A Marks Obtainable row. Ten per CA test, forty for the terminal column.

    Numbers chosen to make the arithmetic obvious in the assertions, **not**
    because the school uses them — N2 is open and nothing in the application
    defaults these.
    """
    row: dict[str, Decimal | None] = {
        "ca_test_1": Decimal(10),
        "ca_test_2": Decimal(10),
        "ca_test_3": Decimal(10),
        "ca_test_4": Decimal(10),
        "ca_test_5": Decimal(10),
        "mid_term_test": Decimal(40),
        "exam": Decimal(40),
    }
    for column, value in overrides.items():
        row[column] = None if value is None else Decimal(value)
    return row


def scores(**values: str) -> dict[str, Decimal | None]:
    return {column: Decimal(value) for column, value in values.items()}


# ---------------------------------------------------------------------------
# Properties that hold whatever N3 turns out to be
# ---------------------------------------------------------------------------


def test_a_full_first_half_row_is_a_percentage_of_the_marks_obtainable() -> None:
    full = scores(
        ca_test_1="10",
        ca_test_2="10",
        ca_test_3="10",
        ca_test_4="10",
        ca_test_5="10",
        mid_term_test="40",
    )

    assert mid_term_average(full, maxima()) == Decimal("100.00")


def test_an_entirely_blank_row_has_no_average() -> None:
    """Not zero. A pupil nobody has entered yet has no average, and a zero
    would print on the card as if it had been earned."""
    assert mid_term_average({}, maxima()) is None
    assert total_weighted_average({"exam": None}, maxima()) is None


def test_a_blank_cell_counts_as_zero_once_the_row_has_started() -> None:
    """Consistent with R2, which is the point.

    The CA Test Total column beside it is generated by Postgres as
    COALESCE(...) + ..., so it reads low on a half-entered row. If the average
    treated a blank as "unknown" instead, the two figures printed side by side
    would disagree about the same row.
    """
    half_entered = scores(ca_test_1="10", ca_test_2="10")

    # 20 earned out of 90 obtainable.
    assert mid_term_average(half_entered, maxima()) == Decimal("22.22")


def test_a_column_with_no_maximum_is_not_on_the_sheet() -> None:
    """A school using three CA tests sets three maxima, and the average is out
    of those three plus the terminal column — not out of five."""
    three_tests = maxima(ca_test_4=None, ca_test_5=None)
    full = scores(ca_test_1="10", ca_test_2="10", ca_test_3="10", mid_term_test="40")

    assert mid_term_average(full, three_tests) == Decimal("100.00")


def test_a_score_against_a_column_that_is_not_on_the_sheet_is_ignored() -> None:
    """Defence in depth: R1 rejects this at the boundary, but the formula must
    not quietly fold an exam mark into a first-half average either."""
    with_stray_exam = scores(ca_test_1="10", exam="40")

    assert mid_term_average(with_stray_exam, maxima()) == Decimal("11.11")


def test_the_two_halves_read_their_own_terminal_column() -> None:
    first = scores(ca_test_1="10", mid_term_test="40")
    second = scores(ca_test_1="10", exam="40")

    assert mid_term_average(first, maxima()) == Decimal("55.56")
    assert total_weighted_average(second, maxima()) == Decimal("55.56")
    # Each ignores the other's column entirely.
    assert mid_term_average(second, maxima()) == Decimal("11.11")
    assert total_weighted_average(first, maxima()) == Decimal("11.11")


def test_period_average_dispatches_on_the_half() -> None:
    """The single entry point, so no caller picks the formula for itself."""
    row = scores(ca_test_1="5", mid_term_test="20", exam="40")

    assert period_average(TermHalf.FIRST_HALF, row, maxima()) == mid_term_average(row, maxima())
    assert period_average(TermHalf.SECOND_HALF, row, maxima()) == total_weighted_average(
        row, maxima()
    )


def test_a_sheet_with_no_maxima_at_all_has_no_average() -> None:
    """Dividing by nothing. R1 refuses the entry long before this, but the
    formula must not raise if it is ever reached another way."""
    nothing = dict.fromkeys(maxima(), None)

    assert mid_term_average(scores(ca_test_1="5"), nothing) is None


def test_the_average_is_scale_free() -> None:
    """Whatever N2 turns out to be, the result is in the 0-100 the grade bands
    describe. Marks out of 7 and marks out of 700 give the same average."""
    small = {"ca_test_1": Decimal(7), "mid_term_test": None, "exam": None}
    large = {"ca_test_1": Decimal(700), "mid_term_test": None, "exam": None}
    for column in ("ca_test_2", "ca_test_3", "ca_test_4", "ca_test_5"):
        small[column] = None
        large[column] = None

    assert mid_term_average({"ca_test_1": Decimal(5)}, small) == Decimal("71.43")
    assert mid_term_average({"ca_test_1": Decimal(500)}, large) == Decimal("71.43")


def test_the_average_fits_the_column_it_is_stored_in() -> None:
    """`result_entries.period_average` is numeric(5,2); an unrounded third of
    a mark would be truncated by the database instead of here."""
    third = mid_term_average(scores(ca_test_1="10", ca_test_2="10", ca_test_3="10"), maxima())

    assert third is not None
    assert third.as_tuple().exponent == -2


# ---------------------------------------------------------------------------
# R4 — and the rounding assumption N3 has not answered (§14 A17)
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("average", "letter"),
    [
        ("100.00", "A+"),
        ("90.00", "A+"),
        ("89.49", "A"),
        ("80.00", "A"),
        ("70.00", "B+"),
        ("60.00", "B"),
        ("50.00", "C"),
        ("40.00", "D"),
        ("0.00", "E"),
    ],
)
def test_a_whole_average_lands_in_the_band_the_card_prints(average: str, letter: str) -> None:
    band = band_for(Decimal(average), CARD_BANDS)

    assert band is not None
    assert band.letter == letter


def test_the_gap_between_bands_is_closed_by_rounding_half_up() -> None:
    """**The N3 assumption, pinned.**

    The card's bands leave 39.5 in no band (docs/DECISIONS.md D43). Rather
    than print an empty grade cell, `banded_value` rounds half up before the
    lookup — so 39.5 is a D and 39.49 is an E.

    This is an assumption, recorded in §14 as A17. When the school answers the
    second half of N3 this test is the one that changes, and it is meant to:
    changing it is how the decision gets made on purpose.
    """
    assert banded_value(Decimal("39.50")) == Decimal(40)
    assert banded_value(Decimal("39.49")) == Decimal(39)

    assert band_for(Decimal("39.50"), CARD_BANDS).letter == "D"
    assert band_for(Decimal("39.49"), CARD_BANDS).letter == "E"


def test_no_average_means_no_grade() -> None:
    assert band_for(None, CARD_BANDS) is None


def test_a_value_no_band_covers_has_no_grade() -> None:
    """A missing grade beats a wrong one.

    `create_scale` refuses a scale with gaps, so this should be unreachable —
    but a scale seeded before that rule existed could have one, and the cell
    must then print empty rather than borrow the nearest band.
    """
    sparse = [GradeBand(letter="A", remark="Top", min_score=Decimal(90), max_score=Decimal(100))]

    assert band_for(Decimal("50.00"), sparse) is None


def test_no_bands_at_all_means_no_grade() -> None:
    """A school that has not set up a scale yet still gets a usable grid."""
    assert band_for(Decimal("75.00"), []) is None
