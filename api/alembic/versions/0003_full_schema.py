# times_present must not exceed it. Enforced here *and* in services/results.py
# (§4.7) so that no path - a script, psql, a future endpoint - can write a row
# that breaks it.
#
# A NULL times_school_opened means the admin has not set the term's calendar
# yet, so there is nothing to check against and the row is allowed.
ATTENDANCE_TRIGGER_FUNCTION = """
CREATE OR REPLACE FUNCTION check_attendance_bounds() RETURNS trigger AS $$
DECLARE
    opened int;
BEGIN
    SELECT times_school_opened INTO opened FROM terms WHERE id = NEW.term_id;

    IF opened IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.times_present > opened THEN
        RAISE EXCEPTION
            'times_present (%) exceeds times_school_opened (%) for this term',
            NEW.times_present, opened;
    END IF;

    IF NEW.times_present + NEW.times_absent <> opened THEN
        RAISE EXCEPTION
            'times_present + times_absent (%) must equal times_school_opened (%)',
            NEW.times_present + NEW.times_absent, opened;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
"""

# The other direction: changing times_school_opened after attendance has been
# recorded would leave rows that the rule above forbids. Refuse the change and
# say how many rows disagree, rather than let the invariant rot.
TERM_TRIGGER_FUNCTION = """
CREATE OR REPLACE FUNCTION check_term_attendance_consistency() RETURNS trigger AS $$
DECLARE
    offending int;
BEGIN
    IF NEW.times_school_opened IS NULL
       OR NEW.times_school_opened IS NOT DISTINCT FROM OLD.times_school_opened THEN
        RETURN NEW;
    END IF;

    SELECT count(*) INTO offending
    FROM attendance_records
    WHERE term_id = NEW.id
      AND times_present + times_absent <> NEW.times_school_opened;

    IF offending > 0 THEN
        RAISE EXCEPTION
            'cannot set times_school_opened to %: % attendance record(s) would no longer add up',
            NEW.times_school_opened, offending;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
"""


